/// Shared spacing values following the proposed 4/8 px rhythm.
abstract final class AppSpacing {
  static const xxs = 4.0;
  static const xs = 8.0;
  static const sm = 12.0;
  static const md = 16.0;
  static const lg = 20.0;
  static const xl = 24.0;
  static const xxl = 32.0;
}

/// Width limits shared by the student and lecturer experiences.
abstract final class AppBreakpoints {
  static const compact = 600.0;
  static const desktop = 1024.0;
  static const studentContentMaxWidth = 480.0;
  static const lecturerContentMaxWidth = 1120.0;
}
